-- Additive support for the inquiry ticket system (ticket numbers, private reply threads, priorities,
-- archiving, soft deletion) and the wider roadmap/feedback status vocabulary used by the hub and admin UI.
-- Existing columns, tables and rows are left untouched. Run once (supabase db push or the SQL editor).

alter table public.feedback add column if not exists ticket_number bigint generated by default as identity;
alter table public.feedback add column if not exists access_token_hash text;
alter table public.feedback add column if not exists priority text not null default 'medium';
alter table public.feedback add column if not exists archived_at timestamptz;
alter table public.feedback add column if not exists deleted_at timestamptz;
create unique index if not exists feedback_ticket_number_idx on public.feedback (ticket_number);

-- Status vocabularies grew (for example under_review, released); drop the old narrow checks if they exist.
alter table public.feedback drop constraint if exists feedback_status_check;
alter table public.roadmap drop constraint if exists roadmap_status_check;
alter table public.roadmap drop constraint if exists roadmap_priority_check;

create table if not exists public.feedback_conversations (
  id bigint generated always as identity primary key,
  feedback_id text not null,
  author_type text not null check (author_type in ('user', 'admin')),
  message text not null,
  created_at timestamptz not null default now()
);
create index if not exists feedback_conversations_feedback_idx on public.feedback_conversations (feedback_id, created_at);

create table if not exists public.feedback_activity (
  id bigint generated always as identity primary key,
  feedback_id text not null,
  action text not null,
  actor_type text not null,
  created_at timestamptz not null default now()
);
create index if not exists feedback_activity_feedback_idx on public.feedback_activity (feedback_id, created_at);

alter table public.feedback_conversations enable row level security;
alter table public.feedback_activity enable row level security;
